// @vitest-environment jsdom
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { soundEvents } from '../sound/events.ts';
import { COUNTDOWN_FROM, countdownRate } from '../sound/countdown.ts';
import { felt } from '../sound/packs/felt/index.ts';
import { arcade } from '../sound/packs/arcade/index.ts';
import { glass } from '../sound/packs/glass/index.ts';
import { web } from '../sound/packs/web/index.ts';

const SOUND_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'sound');
const STORAGE_KEY = 'ot.sound';

const PACKS = [felt, arcade, glass, web];

function walkVendoredFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) {
      out.push(...walkVendoredFiles(full));
    } else if (entry.endsWith('.ts') && entry !== 'index.ts') {
      out.push(full);
    }
  }
  return out;
}

beforeEach(() => {
  window.localStorage.clear();
  vi.resetModules();
});

afterEach(() => {
  vi.doUnmock('../sound/packs/felt/index.ts');
});

describe('packs', () => {
  it('map every sound event', () => {
    for (const pack of PACKS) {
      expect(Object.keys(pack.sounds).sort()).toEqual([...soundEvents].sort());
    }
  });

  it('have unique ids', () => {
    const ids = PACKS.map((pack) => pack.id);
    expect(new Set(ids).size).toBe(ids.length);
  });
});

describe('provenance', () => {
  const forbidden = /bell-toll|blizzard|voiceover-pack|quest|warcraft|alliance|horde|night-elf/i;

  it('vendors no sound whose name or content matches the forbidden Warcraft/Blizzard collection', () => {
    const files = walkVendoredFiles(path.join(SOUND_DIR, 'packs'));
    expect(files.length).toBeGreaterThan(0);
    for (const file of files) {
      const name = path.basename(file, '.ts');
      expect(name).not.toMatch(forbidden);
      const content = readFileSync(file, 'utf8');
      expect(content).not.toMatch(forbidden);
      expect(content).toMatch(/license:\s*"CC0"/);
    }
  });

  /* Two provenance stories, so the check is per pack rather than one blanket
     author: the first three packs are vendored Kenney files, and web is
     synthesised in this repo by a script anyone can rerun. */
  it('attributes every sound to the pack it actually came from', () => {
    for (const file of walkVendoredFiles(path.join(SOUND_DIR, 'packs'))) {
      const content = readFileSync(file, 'utf8');
      if (file.includes(`${path.sep}web${path.sep}`)) {
        expect(content).toMatch(/author:\s*"EveryonePoker"/);
        expect(content).toMatch(/Generated by client\/scripts\/sound-web\.mjs/);
      } else {
        expect(content).toMatch(/author:\s*"Kenney"/);
      }
    }
  });
});

describe('persistence', () => {
  it('falls back to defaults with nothing stored', async () => {
    const mod = await import('../sound/index.ts');
    expect(mod.sound.state).toEqual({ enabled: true, volume: 0.6, pack: 'felt' });
  });

  it('loads persisted state on init', async () => {
    window.localStorage.setItem(STORAGE_KEY, JSON.stringify({ enabled: true, volume: 0.3, pack: 'glass' }));
    const mod = await import('../sound/index.ts');
    expect(mod.sound.state).toEqual({ enabled: true, volume: 0.3, pack: 'glass' });
  });

  it('round-trips writes through localStorage', async () => {
    const mod = await import('../sound/index.ts');
    mod.sound.setEnabled(true);
    mod.sound.setVolume(0.9);
    mod.sound.setPack('arcade');

    const stored = JSON.parse(window.localStorage.getItem(STORAGE_KEY) ?? '{}');
    expect(stored).toEqual({ enabled: true, volume: 0.9, pack: 'arcade' });

    vi.resetModules();
    const reloaded = await import('../sound/index.ts');
    expect(reloaded.sound.state).toEqual({ enabled: true, volume: 0.9, pack: 'arcade' });
  });

  it('ignores a garbage stored value rather than throwing', async () => {
    window.localStorage.setItem(STORAGE_KEY, 'not json');
    const mod = await import('../sound/index.ts');
    expect(mod.sound.state).toEqual({ enabled: true, volume: 0.6, pack: 'felt' });
  });
});

/* The ready check's countdown. The rule is "the last ten seconds tick and
   they climb", which is one sentence and four ways to get it wrong: ticking
   before the countdown, ticking after it has run out, climbing the wrong way,
   and climbing so far that the sample stops sounding like itself. */
describe('the countdown rate', () => {
  it('ticks the last ten seconds and nothing before or after them', () => {
    expect(countdownRate(COUNTDOWN_FROM + 1)).toBeNull();
    expect(countdownRate(20)).toBeNull();
    expect(countdownRate(0)).toBeNull();
    expect(countdownRate(-1)).toBeNull();
    for (let left = 1; left <= COUNTDOWN_FROM; left++) {
      expect(countdownRate(left), `${left} seconds left`).not.toBeNull();
    }
  });

  it('starts at the sample\'s own pitch and climbs as it runs down', () => {
    expect(countdownRate(COUNTDOWN_FROM)).toBe(1);
    const rates = [];
    for (let left = COUNTDOWN_FROM; left >= 1; left--) rates.push(countdownRate(left)!);
    for (let i = 1; i < rates.length; i++) {
      expect(rates[i], `tick ${i} is higher than the one before it`).toBeGreaterThan(rates[i - 1]);
    }
    // Far enough to feel, near enough that it is still the same tick.
    expect(rates[rates.length - 1]).toBeGreaterThan(1.3);
    expect(rates[rates.length - 1]).toBeLessThan(1.5);
  });

  it('gives one number per second rather than a float that drifts', () => {
    expect(countdownRate(4)).toBe(countdownRate(4.2));
    expect(countdownRate(7)).toBe(0.05 * 3 + 1);
    expect(countdownRate(Number.NaN)).toBeNull();
    expect(countdownRate(Number.POSITIVE_INFINITY)).toBeNull();
  });
});

describe('playback gating', () => {
  it('is a no-op before unlock and never throws', async () => {
    const mod = await import('../sound/index.ts');
    mod.sound.setEnabled(true);
    await expect(mod.sound.play('deal')).resolves.toBeUndefined();
  });

  it('is a no-op while disabled', async () => {
    const mod = await import('../sound/index.ts');
    await mod.sound.unlock();
    await expect(mod.sound.play('deal')).resolves.toBeUndefined();
  });

  /* A rate is an option on the same call, so a caller that passes one is
     gated exactly like one that does not. */
  it('takes a playback rate without changing whether it plays at all', async () => {
    const mod = await import('../sound/index.ts');
    mod.sound.setEnabled(true);
    await expect(mod.sound.play('tick', { rate: 1.45 })).resolves.toBeUndefined();
    mod.sound.setEnabled(false);
    await expect(mod.sound.play('tick', { rate: 1.45 })).resolves.toBeUndefined();
  });
});

describe('pack loading', () => {
  it('loads a pack lazily via dynamic import, once per pack', async () => {
    let loadCount = 0;
    vi.doMock('../sound/packs/felt/index.ts', () => {
      loadCount += 1;
      return {
        default: {
          id: 'felt',
          name: 'Felt',
          description: 'mock',
          sounds: Object.fromEntries(soundEvents.map((event) => [event, null])),
        },
      };
    });

    const mod = await import('../sound/index.ts');
    expect(loadCount).toBe(0);

    mod.sound.setEnabled(true);
    mod.sound.setPack('felt');
    await mod.sound.play('deal');
    await mod.sound.play('cardPlace');

    expect(loadCount).toBe(1);
  });

  it('exposes pack metadata without loading any audio module', async () => {
    const mod = await import('../sound/index.ts');
    expect(mod.sound.packs).toEqual([
      { id: 'felt', name: 'Felt', description: expect.any(String) },
      { id: 'arcade', name: 'Arcade', description: expect.any(String) },
      { id: 'glass', name: 'Glass', description: expect.any(String) },
      { id: 'web', name: 'Old web', description: expect.any(String) },
    ]);
  });
});
